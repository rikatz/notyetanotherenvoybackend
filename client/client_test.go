func TestNewADSClient_AutoGeneratedName(t *testing.T) {
	cfg := Config{
		ServerAddress:        "localhost:9978",
		Namespace:            "test-ns",
		GatewayName:          "test-gateway",
		Token:                "test-token",
		ResourceTypeHandlers: ResourceTypeStore{},
	}

	client1, err := NewADSClient(cfg)
	if err != nil {
		t.Fatalf("Expected no error, got: %v", err)
	}

	client2, err := NewADSClient(cfg)
	if err != nil {
		t.Fatalf("Expected no error, got: %v", err)
	}

	// Auto-generated names should be different (random suffix)
	name1 := client1.nodeInfo.Metadata.Fields["NAME"].GetStringValue()
	name2 := client2.nodeInfo.Metadata.Fields["NAME"].GetStringValue()

	if name1 == name2 {
		t.Errorf("Expected different auto-generated names, both are '%s'", name1)
	}

	// Both should start with gateway name
	if len(name1) <= len("test-gateway") {
		t.Errorf("Expected auto-generated name to have suffix, got '%s'", name1)
	}
}

