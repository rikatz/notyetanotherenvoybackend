func TestNewADSClient_InvalidServerAddress(t *testing.T) {
	testCases := []struct {
		name    string
		address string
	}{
		{"no port", "localhost"},
		{"invalid format", "not-a-valid-address"},
	}

	for _, tc := range testCases {
		t.Run(tc.name, func(t *testing.T) {
			cfg := Config{
				ServerAddress:        tc.address,
				Namespace:            "test-ns",
				GatewayName:          "test-gateway",
				Token:                "test-token",
				ResourceTypeHandlers: ResourceTypeStore{},
			}

			_, err := NewADSClient(cfg)
			if err == nil {
				t.Fatalf("Expected error for invalid server address '%s'", tc.address)
			}
		})
	}
}

