func TestResourceTypeStore(t *testing.T) {
	handler1 := &mockHandler{}
	handler2 := &mockHandler{}

	store := ResourceTypeStore{
		"type.googleapis.com/istio.workload.Address":             handler1,
		"type.googleapis.com/agentgateway.dev.resource.Resource": handler2,
	}

	if len(store) != 2 {
		t.Errorf("Expected store length 2, got %d", len(store))
	}

	if store["type.googleapis.com/istio.workload.Address"] != handler1 {
		t.Error("Expected handler1 for Address type")
	}

	if store["type.googleapis.com/agentgateway.dev.resource.Resource"] != handler2 {
		t.Error("Expected handler2 for Resource type")
	}
}
