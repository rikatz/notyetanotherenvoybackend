package client

import (
	"context"
	"testing"

	discovery "github.com/envoyproxy/go-control-plane/envoy/service/discovery/v3"
)

// Mock handler for testing
type mockHandler struct {
	updateCalled bool
	removeCalled bool
	updateError  error
	removeError  error
}

func (m *mockHandler) Update(ctx context.Context, resources []*discovery.Resource) error {
	m.updateCalled = true
	return m.updateError
}

func (m *mockHandler) Remove(ctx context.Context, resourceNames []string) error {
	m.removeCalled = true
	return m.removeError
}

func TestNewADSClient_ValidConfig(t *testing.T) {
	handler := &mockHandler{}
	cfg := Config{
		ServerAddress:        "localhost:9978",
		Namespace:            "test-ns",
		GatewayName:          "test-gateway",
		Token:                "test-token",
		ResourceTypeHandlers: ResourceTypeStore{"test.type": handler},
	}

	client, err := NewADSClient(cfg)
	if err != nil {
		t.Fatalf("Expected no error, got: %v", err)
	}

	if client == nil {
		t.Fatal("Expected client to be non-nil")
	}

	if client.token != "test-token" {
		t.Errorf("Expected token 'test-token', got '%s'", client.token)
	}

	if client.nodeInfo == nil {
		t.Fatal("Expected nodeInfo to be non-nil")
	}

	// Verify node metadata
	expectedRole := "test-ns~test-gateway"
	if client.nodeInfo.Metadata.Fields["role"].GetStringValue() != expectedRole {
		t.Errorf("Expected role '%s', got '%s'", expectedRole, client.nodeInfo.Metadata.Fields["role"].GetStringValue())
	}

	if client.nodeInfo.Metadata.Fields["NAMESPACE"].GetStringValue() != "test-ns" {
		t.Errorf("Expected namespace 'test-ns', got '%s'", client.nodeInfo.Metadata.Fields["NAMESPACE"].GetStringValue())
	}

	if client.nodeInfo.Metadata.Fields["GATEWAY"].GetStringValue() != "test-gateway" {
		t.Errorf("Expected gateway 'test-gateway', got '%s'", client.nodeInfo.Metadata.Fields["GATEWAY"].GetStringValue())
	}
}

